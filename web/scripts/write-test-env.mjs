/**
 * Write the LOCAL test-env files from a running Supabase stack.
 *
 *   node scripts/write-test-env.mjs        # from web/
 *
 * Reads `supabase status -o env` (the running local stack) and writes:
 *   - web/.env.test        — vitest integration suites read this
 *   - web/e2e/.env.e2e     — Playwright config + e2e:seed read this
 *
 * Both target http://127.0.0.1:54321 with the local anon/service keys.
 * These keys are LOCAL-ONLY and worthless against any real project, but
 * the files are gitignored anyway. Re-run after every `supabase start`
 * (newer CLI versions mint fresh local keys per stack).
 *
 * SAFETY: refuses to write anything if the API URL is not local.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

function supabaseStatusEnv() {
  // Prefer a supabase on PATH; fall back to npx (matches the rest of the
  // repo, where the CLI is invoked via npx).
  const attempts = [
    ["supabase", ["status", "-o", "env"]],
    ["npx", ["--yes", "supabase", "status", "-o", "env"]],
  ];
  let lastErr;
  for (const [cmd, args] of attempts) {
    try {
      return execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    } catch (err) {
      lastErr = err;
    }
  }
  throw new Error(
    `Could not run \`supabase status -o env\`. Is the stack up (\`supabase start\`)?\n${lastErr?.message ?? ""}`,
  );
}

function parse(envText) {
  const out = {};
  for (const line of envText.split("\n")) {
    const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.+?)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^"|"$/g, "");
  }
  return out;
}

const status = parse(supabaseStatusEnv());

// `supabase status -o env` key names vary slightly by CLI version; accept
// the common aliases.
const apiUrl = status.API_URL ?? status.SUPABASE_URL ?? "http://127.0.0.1:54321";
const anonKey = status.ANON_KEY ?? status.SUPABASE_ANON_KEY;
const serviceKey = status.SERVICE_ROLE_KEY ?? status.SUPABASE_SERVICE_ROLE_KEY;

if (!/127\.0\.0\.1|localhost|0\.0\.0\.0/.test(apiUrl)) {
  console.error(`Refusing to write test env: API_URL "${apiUrl}" is not local.`);
  process.exit(1);
}
if (!anonKey || !serviceKey) {
  console.error("Could not read ANON_KEY / SERVICE_ROLE_KEY from `supabase status -o env`.");
  console.error("Raw status keys seen:", Object.keys(status).join(", "));
  process.exit(1);
}

const webRoot = process.cwd();

const dotEnvTest = [
  "# AUTO-GENERATED by scripts/write-test-env.mjs — do not edit by hand.",
  "# LOCAL Supabase test stack. Safe to delete; regenerate with `pnpm test:setup`.",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
  "PREVIEW_TOKEN_SECRET=test-preview-secret",
  "",
].join("\n");

const dotEnvE2e = [
  "# AUTO-GENERATED by scripts/write-test-env.mjs — do not edit by hand.",
  "# LOCAL Supabase test stack for Playwright. Regenerate with `pnpm test:setup`.",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
  "PREVIEW_TOKEN_SECRET=e2e-preview-secret",
  "E2E_BASE_URL=http://127.0.0.1:3000",
  "",
].join("\n");

writeFileSync(path.join(webRoot, ".env.test"), dotEnvTest, "utf8");
mkdirSync(path.join(webRoot, "e2e"), { recursive: true });
writeFileSync(path.join(webRoot, "e2e", ".env.e2e"), dotEnvE2e, "utf8");

console.log(`✔ Wrote web/.env.test and web/e2e/.env.e2e → ${apiUrl}`);
